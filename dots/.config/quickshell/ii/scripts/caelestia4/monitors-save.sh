#!/usr/bin/env bash
# caelestia4: save the current monitor setup (after the settings app's "Keep these settings?" confirmation) to
# ~/.config/hypr/monitors.lua, one hl.monitor() per connected output, from `hyprctl monitors -j`. Each is matched by
# its description (make, model, serial): the connector name can change between boots (the G95NC was DP-2, then DP-6),
# and a rule for a name that's gone leaves the monitor at its preferred mode (3840x1080@60, scale 1 here).
set -euo pipefail
out="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/monitors.lua"
[[ -f "$out" ]] && cp "$out" "$out.bak"
hyprctl monitors -j | jq -r '
  "-- Generated by the settings app (Display). Previous version: monitors.lua.bak",
  (.[] | "-- \(.description)\nhl.monitor({\n    output = \"desc:\(.description)\",\n    mode = \"\(.width)x\(.height)@\(.refreshRate | . * 100 | round / 100)\",\n    position = \"\(.x)x\(.y)\",\n    scale = \(.scale),\n    transform = \(.transform)\n})")
' > "$out.tmp"
mv "$out.tmp" "$out"
