#!/usr/bin/env bash
# caelestia4: write hypridle's timers from the settings app and restart hypridle.
# Usage: hypridle-timeouts.sh <lock-min> <screen-off-min> <suspend-min> <lock-before-sleep:true|false>   (0 = never)
# hypridle.conf keeps the general block and does `source = ~/.config/hypr/hypridle-timeouts.conf`.
set -euo pipefail
lock=${1:-5} off=${2:-10} sleep=${3:-15} lockbefore=${4:-true}
out="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/hypridle-timeouts.conf"
{
  echo "# Generated by the settings app (Power & idle). Edits here are overwritten; 0 = never."
  echo "general {"
  if [[ "$lockbefore" == true ]]; then echo "    before_sleep_cmd = loginctl lock-session"; else echo "    before_sleep_cmd ="; fi
  echo "}"
  if (( lock > 0 )); then
    printf '\nlistener {\n    timeout = %d\n    on-timeout = loginctl lock-session\n}\n' $((lock * 60))
  fi
  if (( off > 0 )); then
    printf '\nlistener {\n    timeout = %d\n    on-timeout = hyprctl dispatch '"'"'hl.dsp.dpms({ action = "disable" })'"'"'\n    on-resume = hyprctl dispatch '"'"'hl.dsp.dpms({ action = "enable" })'"'"'\n}\n' $((off * 60))
  fi
  if (( sleep > 0 )); then
    printf '\nlistener {\n    timeout = %d\n    on-timeout = systemctl suspend || loginctl suspend\n}\n' $((sleep * 60))
  fi
} > "$out.tmp"
mv "$out.tmp" "$out"

# Restart hypridle the way this session runs it: user unit (uwsm session) or a child of Hyprland (plain session)
if systemctl --user -q is-active hypridle.service 2>/dev/null; then
  systemctl --user restart hypridle.service
else
  pkill -x hypridle || true
  hyprctl dispatch 'hl.dsp.exec_cmd("hypridle")' >/dev/null
fi
