#!/usr/bin/env bash
# caelestia4: hyprlock's own strings in the shell's language. hyprlock.conf can't run a command for its placeholder, so
# they're variables in a file of their own (hyprlock/strings.conf), written before each lock.
source "$(dirname "$(readlink -f "$0")")/tr.sh"
out="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/hyprlock/strings.conf"
line() { printf '$%s = %s\n' "$1" "$(tr_ "$2" | sed 's/#/##/g')"; }
tmp="$out.$$"
{
    echo "# Generated by quickshell/ii/scripts/caelestia4/hyprlock-strings.sh"
    line str_password "Enter password"
    line str_locked_at "Locked at"
    line str_keyboard "Keyboard"
} > "$tmp" && mv -f "$tmp" "$out"
